"""The listings CSV and the generated INDEX.md.

ROWS_LOCK is the one lock shared by the analysis worker and the polling thread (score corrections): hold it around
every read-modify-write of listings.csv, INDEX.md and listings/NNN.json.
"""

import csv
import threading
import time
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from deal_scout.domain import Domain
from deal_scout.feedback import corrections_text
from deal_scout.prompts import Listing
from deal_scout.scoring import clean, ordered_specs, score, specs_avg

Row = dict[str, Any]  # one listings.csv row

# A lock is not "state" in the sense of the no-global-mutable-state rule: it guards files, and holds no data.
ROWS_LOCK = threading.Lock()


def csv_fields(d: Domain) -> list[str]:
    """Return the CSV column names for the domain, in order."""
    return (
        ["number", "title", "seller", "source", "location", "link", "price_pln", "price_net", "model"]
        + list(d.categories)
        + [
            "year",
            "mileage_km",
            "fair_price_low",
            "fair_price_high",
            "score",
            "specs_avg",
            "met",
            "missed",
            "unknown",
            "deal_breakers_hit",
            "missing",
            "red_flags",
            "corrections",
            "verdict",
            "status",
            "first_seen",
            "processed",
        ]
        + d.specs
    )


def csv_row(n: int, data: Listing, d: Domain, old: Row | None = None, link: str = "") -> Row:
    """Build listing n's CSV row from the analysis, keeping the status and first-seen date of the old row."""
    old = old or {}
    checks = data.get("criteria_checks") or []

    def count(result: str) -> int:
        return sum(1 for c in checks if c["result"] == result)

    s = score(checks)
    avg = specs_avg(data, d.specs)
    row: Row = {
        "number": n,
        "title": data.get("title", ""),
        "seller": data.get("seller_name") or "",
        "source": data.get("source") or "",
        "location": data.get("location") or "",
        "price_net": "yes" if data.get("price_net") else "",
        "fair_price_low": data.get("fair_price_low") or "",
        "fair_price_high": data.get("fair_price_high") or "",
        "link": link,
        "price_pln": data.get("price_pln") if data.get("price_pln") is not None else "",
        "model": data.get("model") or "",
        "year": data.get("year") or "",
        "mileage_km": data.get("mileage_km") if data.get("mileage_km") is not None else "",
        "score": "" if s is None else s,
        "specs_avg": "" if avg is None else avg,
        "met": count("met"),
        "missed": count("missed"),
        "unknown": count("unknown"),
        "deal_breakers_hit": "; ".join(
            clean(c["criterion"]) for c in checks if c["deal_breaker"] and c["result"] == "missed"
        ),
        "missing": "; ".join(data.get("missing") or []),
        "red_flags": "; ".join(data.get("red_flags") or []),
        "corrections": corrections_text(data),
        "verdict": data.get("verdict", ""),
        "status": old.get("status") or "new",
        "first_seen": old.get("first_seen") or time.strftime("%Y-%m-%d"),
        "processed": time.strftime("%Y-%m-%d %H:%M"),
    }
    for key in d.categories:
        row[key] = data.get(key) or ""
    for name, value, sc in ordered_specs(data, d.specs):
        row[name] = value if sc is None else f"{value} ({sc}/10)"
    return row


def read_rows(path: Path) -> dict[int, Row]:
    """Read listings.csv into rows keyed by listing number; empty if the file does not exist."""
    if not path.exists():
        return {}
    with open(path, encoding="utf-8-sig", newline="") as f:
        rows = {int(r["number"]): r for r in csv.DictReader(f) if r.get("number", "").isdigit()}
    for r in rows.values():  # files written before the "model" column was generalised from "base_vehicle"
        if not r.get("model") and r.get("base_vehicle"):
            r["model"] = r["base_vehicle"]
    return rows


def write_rows(path: Path, rows: Mapping[int, Row], fields: list[str]) -> None:
    """utf-8-sig so Excel shows Polish letters correctly; Numbers and Google Sheets open it too."""
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        for n in sorted(rows):
            w.writerow(rows[n])


def sort_key(row: Row) -> tuple[bool, float, int]:
    """Order rows by score, best first, with unscored rows last and ties by number."""
    s = row.get("score")
    return (s in ("", None), -float(s) if s not in ("", None) else 0, int(row["number"]))


def write_index(path: Path, rows: Mapping[int, Row]) -> None:
    """Write listings/INDEX.md, one table row per listing, best score first."""
    lines = [
        "# Listings (generated by deal-scout from listings.csv; edit status in the CSV)",
        "",
        "| # | Title | Price PLN | Model | Year | km | Score | Status | Verdict |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in sorted(rows.values(), key=sort_key):
        cells = [
            r["number"],
            r["title"],
            r["price_pln"] or "?",
            r["model"] or "?",
            r["year"] or "?",
            r["mileage_km"] or "?",
            "-" if r["score"] in ("", None) else r["score"],
            r["status"],
            r["verdict"],
        ]
        lines.append("| " + " | ".join(str(c).replace("|", "/") for c in cells) + " |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def same_seller(n: int, rows: Mapping[int, Row]) -> list[int]:
    """Other listings from a seller with the same name: a hint of a dealer posing as a private seller, or a repost."""
    name = " ".join(str(rows[n].get("seller") or "").lower().split())
    if not name:
        return []
    return [m for m in sorted(rows) if m != n and " ".join(str(rows[m].get("seller") or "").lower().split()) == name]
